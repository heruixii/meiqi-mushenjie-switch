def translate_button(source: str, key: str = "") -> str:
    if key in BUTTON_ID_EXACT:
        return BUTTON_ID_EXACT[key]
    if source in BUTTON_EXACT:
        return BUTTON_EXACT[source]
    for japanese, chinese in RULES:
        if source == japanese:
            return chinese
    value = source
    for japanese, chinese in TOKEN_RULES:
        value = value.replace(japanese, chinese)
    value = value.replace("　", " ").replace("（", "(").replace("）", ")")
    value = value.replace("時に", "时").replace("時、", "时，")
    value = value.replace("中に", "中").replace("の場合は", "时")
    value = value.replace("の", "的").replace("を", "").replace("に", "")
    value = value.replace("で", "").replace("が", "").replace("は", "")
    value = value.replace("へ", "到").replace("と", "和")
    value = value.replace("・", "/")
    value = value.replace("（画面右的", "（画面右的")
    value = re.sub(r"\s+", " ", value).strip()
    value = value.replace("调整调整", "调整").replace("显示显示", "显示")
    value = value.replace("自动模式到进入", "进入自动模式")
    value = value.replace("跳过模式到进入", "进入跳过模式")
    value = value.replace("窗口关闭", "关闭窗口").replace("菜单关闭", "关闭菜单")
    value = value.replace("菜单打开", "打开菜单").replace("画面返回", "返回画面")
    value = value.replace("标题画面返回", "返回标题画面")
    value = value.replace("选项跳转", "跳转到选项")
    value = value.replace("速度调整", "调整速度").replace("音量调整", "调整音量")
    value = value.replace("的调整", "的调整")
    return value


def has_japanese(value: str) -> bool:
    return bool(re.search(r"[ぁ-んァ-ン]", value))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sheet", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    with args.sheet.open(encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))

    batch: list[tuple[str, str]] = []
    unresolved: list[tuple[str, str]] = []
    for row in rows:
        if row.get("translation") or row.get("file") not in TARGETS:
            continue
        if row["id"] == "Config/system.datu8@5548":
            # Internal font metadata, not a player-facing UI string.
            continue
        source = row.get("source", "")
        if not has_japanese(source):
            continue
        if row["id"] in BUTTON_ID_EXACT:
            translation = BUTTON_ID_EXACT[row["id"]]
        elif row["file"] == "Config/event.datu8":
            translation = CHAPTERS.get(source, "")
        elif row["file"] == "Config/system.datu8":
            translation = SYSTEM.get(source, "")
        else:
            translation = translate_button(source, row["id"])
        if not translation or has_japanese(translation):
            unresolved.append((row["id"], source))
            continue
        batch.append((row["id"], translation))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(["id", "translation"])
        writer.writerows(batch)

    print(f"batch_rows={len(batch)}")
    print(f"unresolved={len(unresolved)}")
    for key, source in unresolved:
        print(f"UNRESOLVED {key}: {source}")
    print(f"output={args.output.resolve()}")
    return 1 if unresolved else 0


if __name__ == "__main__":
    raise SystemExit(main())
